@dataclass
class GeneratorConfig:
    """The policy model under evaluation, served behind an OpenAI-compatible API.

    ``api_key`` is unused by most local servers but is required by the client
    library, hence the placeholder default.
    """

    base_url: str
    model: str
    api_key: str = "EMPTY"
    max_tokens: int = 4096

    @classmethod
    def from_env(cls) -> "GeneratorConfig":
        return cls(
            base_url=os.environ.get("GENERATOR_API_BASE", "http://localhost:8000/v1"),
            model=os.environ.get("GENERATOR_MODEL", "local-policy-model"),
            api_key=os.environ.get("GENERATOR_API_KEY", "EMPTY"),
        )


@dataclass
class CorrectorConfig:
    """The frozen auxiliary model used for error repair and error summarisation.

    It is deliberately a different model from the generator: the generator is
    the subject of the experiment, the corrector is part of the fixed harness.
    """

    api_url: str
    model: str
    api_key: str = ""
    correction_max_tokens: int = 8192
    correction_temperature: float = 0.1
    analysis_max_tokens: int = 4096
    analysis_temperature: float = 0.3
    referer: str = "https://localhost"
    title: str = "AutoDS-Solver code corrector"

    @classmethod
    def from_env(cls) -> "CorrectorConfig":
        return cls(
            api_url=os.environ.get(
                "CORRECTOR_API_URL", "https://openrouter.ai/api/v1/chat/completions"
            ),
            model=os.environ.get("CORRECTOR_MODEL", ""),
            api_key=os.environ.get("CORRECTOR_API_KEY", ""),
        )


@dataclass
class ExecutionConfig:
    """Resource limits applied to every generated program."""

    cpu_limit: int = DEFAULT_CPU_LIMIT
    dl_testing_timeout: int = DEFAULT_DL_TESTING_TIMEOUT
    normal_timeout: int = DEFAULT_NORMAL_TIMEOUT
    pin_cpu_affinity: bool = True


@dataclass
class ExperimentConfig:
    """One full experiment: a set of tasks run for a number of episodes."""

    competitions: List[str]
    prompts_path: str
    generator: GeneratorConfig
    corrector: CorrectorConfig
    execution: ExecutionConfig = field(default_factory=ExecutionConfig)
    n_meta: int = N_META
    n_repair: int = N_REPAIR
    max_episodes: int = 1
    node_id: str = "node-0"
    config_adjustment: int = 0
    cuda_device: Optional[str] = None
    initial_temperature: Optional[float] = None
    initial_top_p: Optional[float] = None
    output_root: str = "."
    submit_to_leaderboard: bool = True
    history_file: str = BEST_HISTORICAL_PARAMS_FILE
