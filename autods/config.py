# --------------------------------------------------------------------------- #
# Inference budgets (Algorithm 1)
# --------------------------------------------------------------------------- #

#: N_meta -- the number of outer meta-steps for one task. Each meta-step issues
#: at most one policy-model call, so this is also the worst-case number of
#: reasoning calls per task.
N_META = 10

#: N_repair -- the number of LocalRepair attempts allowed inside a single
#: meta-step. Algorithm 1 runs the inner loop for k = 0..N_repair, i.e. one
#: initial execution plus at most N_repair repairs, so a meta-step performs at
#: most N_repair + 1 executions.
N_REPAIR = 5

#: tau_sim -- semantic-deadlock threshold. The current error log is compared
#: against every previous error log in the history; if the maximum cosine
#: similarity exceeds this value, the trajectory is declared deadlocked and
#: control returns to SATE instead of attempting another local repair.
TAU_SIM = 0.8

#: Sentence encoder used for the deadlock check.
SIMILARITY_MODEL_NAME = "paraphrase-multilingual-MiniLM-L12-v2"

#: Number of timeouts within one meta-step after which the refinement loop
#: abandons the current candidate. This is a harness-level guard rather than a
#: quantity named in Algorithm 1.
